"""
===============================================================================
Multimodal Dataset Loader
===============================================================================

Author
------
Laura Pérez Liens

Description
-----------
Utilities to discover and iterate over the multimodal embedding datasets
generated by the NAP-CNB preprocessing pipeline.

The loader supports the following input modalities:

    - PRIMARY:
        ProtT5 embeddings stored per augmented BLOSUM row as
        ``chunk_XXXXXX_X.npy``.

    - SECONDARY:
        SecondaryBERT embeddings stored once per original window and aligned
        with the augmented BLOSUM rows through ``group_id``.

The samples and their train/validation/test assignment are always defined by
the ``master_split.csv`` file in the ProtT5 directory.

The module reads large files incrementally and uses NumPy memory mapping where
possible, avoiding loading the complete dataset into RAM.

Example
-------
Load only ProtT5:

    selected_features = [Feature.PRIMARY]

Load ProtT5 together with SecondaryBERT:

    selected_features = [
        Feature.PRIMARY,
        Feature.SECONDARY,
    ]

    datasets = discover_datasets("/path/to/data_input_nn")

    for batch in iterate_dataset(
        datasets[0],
        split=TRAIN,
        features=selected_features,
    ):
        X = build_input_matrix(batch, selected_features)
        y = batch["labels"]

===============================================================================
"""

from __future__ import annotations

from collections import OrderedDict
from enum import Enum
from pathlib import Path
from typing import (
    Dict,
    Iterator,
    List,
    Mapping,
    MutableMapping,
    Optional,
    Sequence,
    Union,
)

import numpy as np
import pandas as pd


# =============================================================================
# Split identifiers
# =============================================================================

TRAIN = 0
VALIDATION = 1
TEST = 2

VALID_SPLITS = {TRAIN, VALIDATION, TEST}

# Number of rows read at a time from master_split.csv.
CSV_CHUNK_SIZE = 100_000

# Maximum number of SecondaryBERT chunks retained in RAM simultaneously.
DEFAULT_SECONDARY_CACHE_SIZE = 8


# =============================================================================
# Feature definitions
# =============================================================================

class Feature(str, Enum):
    """Input modalities supported by the dataset loader."""

    PRIMARY = "primary"
    SECONDARY = "secondary"


FeatureLike = Union[Feature, str]


# =============================================================================
# Dataset discovery
# =============================================================================

def _find_secondary_directory(primary_path: Path) -> Optional[Path]:
    """
    Locate the SecondaryBERT directory corresponding to a ProtT5 directory.

    The expected pair is, for example:

        classification_human_mhc-I_HLA-A_blosum_ProtT5_chunks
        classification_human_mhc-I_HLA-A_SecondaryBERT_by_group

    Parameters
    ----------
    primary_path
        Directory containing ``master_split.csv`` and the ProtT5 chunks.

    Returns
    -------
    Path or None
        Matching SecondaryBERT directory, or ``None`` if it is not found.
    """

    primary_name = primary_path.name

    suffixes = (
        "_blosum_ProtT5_chunks",
        "_ProtT5_chunks",
    )

    prefix = None

    for suffix in suffixes:
        if primary_name.endswith(suffix):
            prefix = primary_name[: -len(suffix)]
            break

    if prefix is not None:
        expected = primary_path.parent / f"{prefix}_SecondaryBERT_by_group"

        if expected.is_dir():
            return expected

    # Fallback for slightly different directory naming.
    candidates = sorted(
        path
        for path in primary_path.parent.glob("*SecondaryBERT_by_group")
        if path.is_dir()
    )

    if len(candidates) == 1:
        return candidates[0]

    return None


def discover_datasets(root: Union[str, Path]) -> List[dict]:
    """
    Discover all multimodal datasets below a root directory.

    A dataset is identified from a ``master_split.csv`` file located in a
    ProtT5 chunk directory.

    Parameters
    ----------
    root
        Root directory containing the species/MHC datasets.

    Returns
    -------
    list of dict
        Each dictionary contains:

        ``name``
            Human-readable dataset name.

        ``primary_path``
            Directory containing ProtT5 chunks.

        ``secondary_path``
            Matching SecondaryBERT directory, if found.

        ``master_split``
            Path to ``master_split.csv``.
    """

    root = Path(root).expanduser().resolve()

    if not root.exists():
        raise FileNotFoundError(f"Dataset root does not exist: {root}")

    datasets: List[dict] = []

    for master_split in sorted(root.rglob("master_split.csv")):
        primary_path = master_split.parent

        # Ignore unrelated master_split.csv files that do not contain ProtT5
        # chunks.
        if not any(primary_path.glob("chunk_*_X.npy")):
            continue

        try:
            relative_parent = primary_path.parent.relative_to(root)
            relative_name = str(relative_parent)
        except ValueError:
            relative_name = primary_path.parent.name

        dataset_name = (
            relative_name
            if relative_name not in ("", ".")
            else primary_path.parent.name
        )

        datasets.append(
            {
                "name": dataset_name,
                "primary_path": primary_path,
                "secondary_path": _find_secondary_directory(primary_path),
                "master_split": master_split,
            }
        )

    return datasets


def print_datasets(
    datasets: Sequence[Mapping[str, object]],
) -> None:
    """Print the datasets discovered by :func:`discover_datasets`."""

    print()
    print("=" * 100)
    print(f"Datasets found: {len(datasets)}")
    print("=" * 100)

    for dataset in datasets:
        secondary = dataset.get("secondary_path")
        secondary_status = "yes" if secondary is not None else "no"

        print(
            f"{dataset['name']}\n"
            f"  Primary:   {dataset['primary_path']}\n"
            f"  Secondary: {secondary_status}"
        )

    print()


