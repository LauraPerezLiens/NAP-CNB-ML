# Validation and utility functions
# =============================================================================

def normalize_features(
    features: Optional[Sequence[FeatureLike]],
) -> List[Feature]:
    """
    Convert strings/Feature values into a validated feature list.

    When ``features`` is ``None``, only ProtT5 is selected.
    """

    if features is None:
        return [Feature.PRIMARY]

    if not features:
        raise ValueError("At least one input feature must be selected.")

    normalized: List[Feature] = []

    for feature in features:
        try:
            parsed = (
                feature
                if isinstance(feature, Feature)
                else Feature(feature)
            )
        except ValueError as error:
            valid = ", ".join(item.value for item in Feature)
            raise ValueError(
                f"Unknown feature {feature!r}. Valid features: {valid}"
            ) from error

        if parsed not in normalized:
            normalized.append(parsed)

    return normalized


def _validate_dataset(
    dataset: Mapping[str, object],
    features: Sequence[Feature],
) -> None:
    """Validate the paths required by the selected modalities."""

    required_keys = {"name", "primary_path", "master_split"}
    missing_keys = required_keys.difference(dataset)

    if missing_keys:
        raise KeyError(
            "Dataset dictionary is missing required keys: "
            + ", ".join(sorted(missing_keys))
        )

    primary_path = Path(dataset["primary_path"])
    master_split = Path(dataset["master_split"])

    if not primary_path.is_dir():
        raise FileNotFoundError(
            f"Primary dataset directory does not exist: {primary_path}"
        )

    if not master_split.is_file():
        raise FileNotFoundError(
            f"master_split.csv does not exist: {master_split}"
        )

    if Feature.SECONDARY in features:
        secondary_path = dataset.get("secondary_path")

        if secondary_path is None:
            raise FileNotFoundError(
                f"No SecondaryBERT directory was found for dataset "
                f"{dataset['name']!r}."
            )

        secondary_path = Path(secondary_path)

        required_secondary_files = (
            secondary_path / "group_id.npy",
            secondary_path / "chunks_manifest.csv",
            secondary_path / "chunks",
        )

        for path in required_secondary_files:
            if not path.exists():
                raise FileNotFoundError(
                    f"Required SecondaryBERT resource not found: {path}"
                )


def _load_row_aligned_chunk(
    primary_path: Path,
    chunk_id: int,
    indices: np.ndarray,
    suffix: str,
    feature_name: str,
) -> np.ndarray:
    """
    Load selected rows from a row-aligned embedding chunk.

    This function is currently used to load ProtT5 embeddings.
    """

    chunk_file = (
        primary_path
        / f"chunk_{chunk_id:06d}_{suffix}.npy"
    )

    if not chunk_file.is_file():
        raise FileNotFoundError(
            f"{feature_name} chunk not found: {chunk_file}"
        )

    values = np.load(chunk_file, mmap_mode="r")

    if values.ndim == 0:
        raise RuntimeError(
            f"{feature_name} chunk has no row dimension: {chunk_file}"
        )

    if len(indices) == 0:
        return np.empty((0,), dtype=values.dtype)

    if indices.min() < 0 or indices.max() >= len(values):
        raise IndexError(
            f"Invalid row indices for {chunk_file}. "
            f"Valid range: 0-{len(values) - 1}; "
            f"requested range: {indices.min()}-{indices.max()}."
        )

    # Advanced indexing creates an independent in-memory array containing only
    # the selected samples.
    return np.asarray(values[indices])


