def iterate_dataset(
    dataset: Mapping[str, object],
    split: int = TRAIN,
    features: Optional[
        Sequence[FeatureLike]
    ] = None,
    csv_chunk_size: int = CSV_CHUNK_SIZE,
    secondary_cache_size: int = DEFAULT_SECONDARY_CACHE_SIZE,
) -> Iterator[dict]:
    """
    Iterate over one dataset for a selected split and set of modalities.

    Parameters
    ----------
    dataset
        Dataset dictionary returned by :func:`discover_datasets`.

    split
        One of ``TRAIN``, ``VALIDATION`` or ``TEST``.

    features
        Modalities to load. Values may be :class:`Feature` members or their
        string names. The default is ``[Feature.PRIMARY]``.

    csv_chunk_size
        Number of rows read at a time from ``master_split.csv``.

    secondary_cache_size
        Maximum number of SecondaryBERT chunks retained in the cache.

    Yields
    ------
    dict
        Batch dictionary containing the selected modalities, labels and
        alignment information.
    """

    if split not in VALID_SPLITS:
        raise ValueError(
            f"Invalid split {split!r}. "
            f"Use TRAIN={TRAIN}, "
            f"VALIDATION={VALIDATION} "
            f"or TEST={TEST}."
        )

    if csv_chunk_size <= 0:
        raise ValueError(
            "csv_chunk_size must be greater than zero."
        )

    selected_features = normalize_features(
        features
    )

    _validate_dataset(
        dataset,
        selected_features,
    )

    primary_path = Path(
        dataset["primary_path"]
    )

    master_split = Path(
        dataset["master_split"]
    )

    total_chunks = sum(
        1
        for _ in primary_path.glob(
            "chunk_*_X.npy"
        )
    )

    if total_chunks == 0:
        raise FileNotFoundError(
            f"No ProtT5 chunk files were found in {primary_path}."
        )

    secondary_store: Optional[
        SecondaryBERTStore
    ] = None

    if Feature.SECONDARY in selected_features:
        secondary_store = SecondaryBERTStore(
            dataset["secondary_path"],
            cache_size=secondary_cache_size,
        )

    available_columns = pd.read_csv(
        master_split,
        nrows=0,
    ).columns.tolist()

    required_columns = {
        "chunk_id",
        "row_idx_in_chunk",
        "y",
        "group_id",
        "split_id",
    }

    missing_columns = (
        required_columns.difference(
            available_columns
        )
    )

    if missing_columns:
        raise ValueError(
            f"{master_split} is missing required columns: "
            + ", ".join(
                sorted(missing_columns)
            )
        )

    usecols = [
        "chunk_id",
        "row_idx_in_chunk",
        "y",
        "group_id",
        "split_id",
    ]

    has_protein_group_id = (
        "protein_group_id"
        in available_columns
    )

    if has_protein_group_id:
        usecols.append(
            "protein_group_id"
        )

    reader = pd.read_csv(
        master_split,
        usecols=usecols,
        chunksize=csv_chunk_size,
    )

    for csv_block in reader:
        split_block = csv_block.loc[
            csv_block["split_id"] == split
        ]

        if split_block.empty:
            continue

        # sort=False preserves the order in which chunk IDs appear in the CSV.
        for chunk_id, rows in split_block.groupby(
            "chunk_id",
            sort=False,
        ):
            chunk_id = int(
                chunk_id
            )

            indices = rows[
                "row_idx_in_chunk"
            ].to_numpy(
                dtype=np.int64,
                copy=False,
            )

            labels = rows[
                "y"
            ].to_numpy(
                dtype=np.uint8,
                copy=False,
            )

            group_ids = rows[
                "group_id"
            ].to_numpy(
                dtype=np.int64,
                copy=False,
            )

            loaded_features: Dict[
                str,
                np.ndarray,
            ] = {}

            # -------------------------------------------------------------
            # PRIMARY — ProtT5
            # -------------------------------------------------------------

            if Feature.PRIMARY in selected_features:
                loaded_features[
                    Feature.PRIMARY.value
                ] = _load_row_aligned_chunk(
                    primary_path=primary_path,
                    chunk_id=chunk_id,
                    indices=indices,
                    suffix="X",
                    feature_name="ProtT5",
                )

            # -------------------------------------------------------------
            # SECONDARY — SecondaryBERT
            # -------------------------------------------------------------

            if Feature.SECONDARY in selected_features:
                assert secondary_store is not None

                loaded_features[
                    Feature.SECONDARY.value
                ] = secondary_store.get(
                    group_ids
                )

            batch = {
                "dataset": dataset["name"],
                "chunk_id": chunk_id,
                "total_chunks": total_chunks,
                "features": loaded_features,
                "labels": labels,
                "group_id": group_ids,
                "row_idx_in_chunk": indices,
            }

            if has_protein_group_id:
                batch[
                    "protein_group_id"
                ] = rows[
                    "protein_group_id"
                ].to_numpy(
                    dtype=np.int64,
                    copy=False,
                )

            yield batch


