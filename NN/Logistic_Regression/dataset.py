def build_input_matrix(
    batch: Mapping[str, object],
    features: Optional[
        Sequence[FeatureLike]
    ] = None,
    dtype: Optional[
        np.dtype
    ] = np.float32,
) -> np.ndarray:
    """
    Concatenate selected modalities into a two-dimensional feature matrix.

    This helper is intended for models such as logistic regression, random
    forests or support-vector machines. Neural networks may instead consume
    ``batch["features"]`` directly and process each modality separately.

    Any feature with more than two dimensions is flattened from the second
    dimension onward.

    Parameters
    ----------
    batch
        Batch returned by :func:`iterate_dataset`.

    features
        Order in which modalities are concatenated. When omitted, the
        insertion order in ``batch["features"]`` is used.

    dtype
        Output dtype. Set to ``None`` to preserve NumPy's inferred dtype.

    Returns
    -------
    ndarray
        Matrix with shape ``(n_samples, total_features)``.
    """

    if "features" not in batch:
        raise KeyError(
            "The batch does not contain a 'features' dictionary."
        )

    batch_features = batch[
        "features"
    ]

    if not isinstance(
        batch_features,
        Mapping,
    ):
        raise TypeError(
            "batch['features'] must be a mapping."
        )

    if features is None:
        selected = [
            Feature(name)
            for name in batch_features.keys()
        ]
    else:
        selected = normalize_features(
            features
        )

    matrices: List[
        np.ndarray
    ] = []

    expected_rows: Optional[
        int
    ] = None

    for feature in selected:
        key = feature.value

        if key not in batch_features:
            raise KeyError(
                f"Feature {key!r} is not present in this batch. "
                f"Available features: {list(batch_features.keys())}"
            )

        values = np.asarray(
            batch_features[key]
        )

        if values.ndim == 0:
            raise ValueError(
                f"Feature {key!r} has no sample dimension."
            )

        if values.ndim == 1:
            values = values.reshape(
                -1,
                1,
            )

        elif values.ndim > 2:
            values = values.reshape(
                values.shape[0],
                -1,
            )

        if expected_rows is None:
            expected_rows = len(
                values
            )

        elif len(values) != expected_rows:
            raise ValueError(
                "Selected modalities contain different numbers "
                "of samples: "
                f"expected {expected_rows}, "
                f"found {len(values)} for {key!r}."
            )

        matrices.append(
            values
        )

    if not matrices:
        raise ValueError(
            "No feature matrices were selected."
        )

    output = (
        matrices[0]
        if len(matrices) == 1
        else np.concatenate(
            matrices,
            axis=1,
        )
    )

    if dtype is not None:
        output = output.astype(
            dtype,
            copy=False,
        )

    return output


def feature_combination_name(
    features: Sequence[FeatureLike],
) -> str:
    """Return a stable name such as ``primary+secondary``."""

    return "+".join(
        feature.value
        for feature in normalize_features(
            features
        )
    )